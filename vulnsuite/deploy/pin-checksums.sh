#!/usr/bin/env bash
# Pin SHA-256 checksums for every binary deploy/Dockerfile downloads.
#
#   deploy/pin-checksums.sh                 # writes deploy/checksums.sha256
#
# Versions are read from the Dockerfile's ARG lines, so bumping a version
# there and re-running this script is the whole workflow. For each artifact
# the script prefers the publisher's own checksum file ("published"); where
# a project publishes none it downloads the artifact and records the hash
# it observed ("computed" — trust-on-first-use). Review the resulting diff
# like any other dependency bump. Only linux/amd64 is pinned.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
dockerfile="$here/Dockerfile"
out="${1:-$here/checksums.sha256}"

ver() { sed -n "s/^ARG $1=\(.*\)$/\1/p" "$dockerfile" | head -n1; }
for v in TRIVY GITLEAKS OSV_SCANNER TRUFFLEHOG DOCKLE KUBESCAPE SUBFINDER HTTPX NUCLEI \
         SYFT COSIGN ZAP TESTSSL KUBECTL HELM BICEP AWSCLI GCLOUD; do
    declare "$v=$(ver "${v}_VERSION")"
    [ -n "${!v}" ] || { echo "ARG ${v}_VERSION not found in $dockerfile" >&2; exit 1; }
done

gh=https://github.com
# "artifact_url|publisher_checksum_file_url"; an empty checksum url means compute.
items=(
  "$gh/aquasecurity/trivy/releases/download/v$TRIVY/trivy_${TRIVY}_Linux-64bit.tar.gz|$gh/aquasecurity/trivy/releases/download/v$TRIVY/trivy_${TRIVY}_checksums.txt"
  "$gh/gitleaks/gitleaks/releases/download/v$GITLEAKS/gitleaks_${GITLEAKS}_linux_x64.tar.gz|$gh/gitleaks/gitleaks/releases/download/v$GITLEAKS/gitleaks_${GITLEAKS}_checksums.txt"
  "$gh/google/osv-scanner/releases/download/v$OSV_SCANNER/osv-scanner_linux_amd64|$gh/google/osv-scanner/releases/download/v$OSV_SCANNER/osv-scanner_SHA256SUMS"
  "$gh/trufflesecurity/trufflehog/releases/download/v$TRUFFLEHOG/trufflehog_${TRUFFLEHOG}_linux_amd64.tar.gz|$gh/trufflesecurity/trufflehog/releases/download/v$TRUFFLEHOG/trufflehog_${TRUFFLEHOG}_checksums.txt"
  "$gh/goodwithtech/dockle/releases/download/v$DOCKLE/dockle_${DOCKLE}_Linux-64bit.tar.gz|$gh/goodwithtech/dockle/releases/download/v$DOCKLE/dockle_${DOCKLE}_checksums.txt"
  "$gh/kubescape/kubescape/releases/download/v$KUBESCAPE/kubescape-ubuntu-latest|$gh/kubescape/kubescape/releases/download/v$KUBESCAPE/checksums.txt"
  "$gh/projectdiscovery/subfinder/releases/download/v$SUBFINDER/subfinder_${SUBFINDER}_linux_amd64.zip|$gh/projectdiscovery/subfinder/releases/download/v$SUBFINDER/subfinder_${SUBFINDER}_checksums.txt"
  "$gh/projectdiscovery/httpx/releases/download/v$HTTPX/httpx_${HTTPX}_linux_amd64.zip|$gh/projectdiscovery/httpx/releases/download/v$HTTPX/httpx_${HTTPX}_checksums.txt"
  "$gh/projectdiscovery/nuclei/releases/download/v$NUCLEI/nuclei_${NUCLEI}_linux_amd64.zip|$gh/projectdiscovery/nuclei/releases/download/v$NUCLEI/nuclei_${NUCLEI}_checksums.txt"
  "$gh/anchore/syft/releases/download/v$SYFT/syft_${SYFT}_linux_amd64.tar.gz|$gh/anchore/syft/releases/download/v$SYFT/syft_${SYFT}_checksums.txt"
  "$gh/sigstore/cosign/releases/download/v$COSIGN/cosign-linux-amd64|$gh/sigstore/cosign/releases/download/v$COSIGN/cosign_checksums.txt"
  "$gh/zaproxy/zaproxy/releases/download/v$ZAP/ZAP_${ZAP}_Linux.tar.gz|"
  "$gh/drwetter/testssl.sh/archive/refs/tags/v$TESTSSL.tar.gz|"
  "https://dl.k8s.io/release/v$KUBECTL/bin/linux/amd64/kubectl|https://dl.k8s.io/release/v$KUBECTL/bin/linux/amd64/kubectl.sha256"
  "https://get.helm.sh/helm-v$HELM-linux-amd64.tar.gz|https://get.helm.sh/helm-v$HELM-linux-amd64.tar.gz.sha256sum"
  "$gh/Azure/bicep/releases/download/v$BICEP/bicep-linux-x64|"
  "https://awscli.amazonaws.com/awscli-exe-linux-x86_64-$AWSCLI.zip|"
  "https://dl.google.com/dl/cloudsdk/channels/rapid/downloads/google-cloud-cli-$GCLOUD-linux-x86_64.tar.gz|"
)

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
{
    echo "# SHA-256 pins for every download in deploy/Dockerfile."
    echo "# Generated by deploy/pin-checksums.sh on $(date -u +%Y-%m-%d); re-run after bumping an ARG *_VERSION."
    echo "# Format: <sha256>  <url>  # published|computed   (published = publisher's checksum file, computed = hashed on download)"
} > "$tmp/out"

fail=0
for item in "${items[@]}"; do
    url="${item%%|*}"
    sums="${item#*|}"
    name="$(basename "$url")"
    hash=""
    source=""
    if [ -n "$sums" ] && curl -fsSL --connect-timeout 20 --max-time 600 --retry 2 -o "$tmp/sums" "$sums"; then
        # goreleaser style: "<hash>  <file>" (file may be prefixed with * or ./)
        hash="$(awk -v n="$name" '{ f=$2; sub(/^\*/, "", f); sub(/^\.\//, "", f); if (f == n) { print $1; exit } }' "$tmp/sums")"
        # bare-hash files (kubectl .sha256, helm .sha256sum)
        [ -n "$hash" ] || hash="$(awk 'NR == 1 && $1 ~ /^[0-9a-f]{64}$/ { print $1 }' "$tmp/sums")"
        [ -n "$hash" ] && source=published
    fi
    if [ -z "$hash" ]; then
        if curl -fsSL --connect-timeout 20 --max-time 600 --retry 2 -o "$tmp/artifact" "$url"; then
            hash="$(sha256sum "$tmp/artifact" | awk '{print $1}')"
            source=computed
            rm -f "$tmp/artifact"
        else
            echo "FAILED  $url" >&2
            fail=1
            continue
        fi
    fi
    printf '%s  %s  # %s\n' "$hash" "$url" "$source" >> "$tmp/out"
    echo "$source  $name" >&2
done

if [ "$fail" != 0 ]; then
    echo "some artifacts could not be pinned; $out NOT written" >&2
    exit 1
fi
mv "$tmp/out" "$out"
echo "wrote $out" >&2
